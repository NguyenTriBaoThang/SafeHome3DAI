export function getQuestionBankByRoomType(roomType: string): SurveyQuestion[] {
  switch (roomType.toUpperCase()) {
    case "BEDROOM":
      return BEDROOM_QUESTIONS;
    case "BATHROOM":
      return BATHROOM_QUESTIONS;
    default:
      return BEDROOM_QUESTIONS;
  }
}

export function getQuestionById(questionId: string): SurveyQuestion | undefined {
  return [...BEDROOM_QUESTIONS, ...BATHROOM_QUESTIONS].find(
    (q) => q.questionId === questionId
  );
}

